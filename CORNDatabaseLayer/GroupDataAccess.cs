        public GroupResponse GroupGetAllDetail()
        {
            GroupResponse response = new GroupResponse();
            IDbConnection mConnection = null;

            mConnection = ProviderFactory.GetConnection(Configuration.ConnectionString, EnumProviders.SQLClient);
            mConnection.Open();

            IDbCommand command = ProviderFactory.GetCommand(EnumProviders.SQLClient);
            command.CommandType = CommandType.StoredProcedure;
            command.CommandText = DBConstants.GroupDBConstant.TBL_GROUP_GET_ALL_DETAIL;
            command.Connection = mConnection;

            IDbDataAdapter da = ProviderFactory.GetAdapter(EnumProviders.SQLClient);
            da.SelectCommand = command;
            DataSet ds = new DataSet();
            da.Fill(ds);

            if (ds.Tables != null && ds.Tables.Count > 0)
            {
                response.GroupList = ds.Tables[0].ToList<Group>();

                List<GroupAccountHead> lstGroupAccountHead = ds.Tables[1].ToList<GroupAccountHead>();

                foreach (Group objGroup in response.GroupList)
                {
                    objGroup.GroupAccountHeadList = (from p in lstGroupAccountHead
                                                     where p.GroupId == objGroup.Id
                                                     select p).ToList();
                }
            }

            return response;
        }
